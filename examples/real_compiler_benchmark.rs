fn main() {
    println!("=== Real Compiler SVM Benchmark ===\n");
    println!("Running a REAL rv32im-to-SVM compiler compiled to rv32im, then to SVM,");
    println!("to compile factorial(10) rv32im code to SVM bytecode.\n");

    // Get the RISC-V code and data
    let code = get_real_compiler_code();
    let data = get_real_compiler_data();
    let rv_instructions = code.len();

    println!("Input Statistics:");
    println!("  Real compiler RISC-V instructions: {}", rv_instructions);
    println!("  Real compiler code size: {} bytes", rv_instructions * 4);
    println!("  Data section: {} words ({} bytes)", data.len(), data.len() * 4);

    // Compile code to SVM
    println!("\nCompiling rv32im to SVM...");
    let program = match compile_binary(&code) {
        Ok(p) => p,
        Err(e) => {
            println!("Compilation failed: {:?}", e);
            return;
        }
    };

    let svm_instructions = program.len();
    let expansion_ratio = svm_instructions as f64 / rv_instructions as f64;

    println!("Compilation Statistics:");
    println!("  SVM instructions: {}", svm_instructions);
    println!("  Expansion ratio: {:.2}x", expansion_ratio);

    // Execute
    println!("\nExecuting meta-compiled real compiler...");
    println!("(Compiling factorial to SVM bytecode 50 times)");

    let mut vm = SvmVm::new(0x20000); // 128KB memory
    vm.set_compute_limit(1_000_000_000); // 1B compute units max

    // Load data section at address 0x10FC (where code ends)
    let data_base = 0x10FC;
    for (i, &word) in data.iter().enumerate() {
        let addr = data_base + i * 4;
        let bytes = word.to_le_bytes();
        vm.memory[addr..addr + 4].copy_from_slice(&bytes);
    }

    let result = match vm.execute(&program) {
        Ok(r) => r,
        Err(e) => {
            println!("Execution failed: {:?}", e);
            println!("Compute units used: {}", vm.compute_units);
            return;
        }
    };

    // Parse result: upper 16 bits = total SVM instructions, lower 16 bits = checksum
    let result_u32 = result as u32;
    let total_svm_insts = (result_u32 >> 16) as u32;
    let checksum = (result_u32 & 0xFFFF) as u32;

    println!("\nResults:");
    println!("  Total SVM instructions generated: {} (50 iterations)", total_svm_insts);
    println!("  SVM instructions per compilation: {}", total_svm_insts / 50);
    println!("  Checksum: 0x{:04x}", checksum);
    println!("\n  Total Compute Units: {}", vm.compute_units);
    println!("  CU per real compiler rv32im instruction: {:.2}",
             vm.compute_units as f64 / rv_instructions as f64);

    // Summary
    println!("\n=== Summary ===\n");
    println!("Meta-compilation pipeline (REAL compiler):");
    println!("  1. C compiler (rv32im_svm_compiler.c) - ~500 lines of C");
    println!("     -> GCC rv32im cross-compiler");
    println!("  2. rv32im binary ({} instructions, {} bytes)", rv_instructions, rv_instructions * 4);
    println!("     -> rv32im-svm compiler");
    println!("  3. SVM bytecode ({} instructions)", svm_instructions);
    println!("     -> SVM interpreter");
    println!("  4. Compiled factorial(10) rv32im -> SVM bytecode {} times", 50);
    println!("\nPerformance:");
    println!("  Meta-compiler CU: {}", vm.compute_units);
    println!("  CU per source rv32im instruction: {:.2}",
             vm.compute_units as f64 / rv_instructions as f64);
    println!("  SVM instructions per factorial compilation: ~{}", total_svm_insts / 50);
}
